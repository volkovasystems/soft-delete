            if [[ -f "$doc" ]]; then
                if ! check_for_duplicates "$doc"; then
                    found_duplicates=1
                fi
            fi
        done
        if [[ $found_duplicates -eq 0 ]]; then
            log_success "No duplicates found in any documentation files"
        else
            log_error "Duplicates found - run with --clean-duplicates to fix"
