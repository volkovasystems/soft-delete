}

# Generate complete directory tree showing ALL files and directories for transparency
generate_directory_tree() {
    # Generate complete tree structure for full transparency
    echo '```'
    echo "soft-delete/"
    
    # Use a comprehensive approach to show ALL files and directories
    # First pass: show all entries with proper tree formatting
    generate_complete_tree_structure "." "" "false"
    
    echo '```'
}

# Helper function to recursively generate complete tree structure
generate_complete_tree_structure() {
    local current_dir="$1"
    local prefix="$2"
    local is_last="$3"
    
    # Skip .git directory for readability but include everything else
    if [[ "$(basename "$current_dir")" == ".git" ]]; then
        return
    fi
    
    # Get all entries (files and directories) sorted
    local entries=()
    while IFS= read -r -d '' entry; do
        entries+=("$entry")
    done < <(find "$current_dir" -maxdepth 1 -mindepth 1 ! -name ".git" -print0 | sort -z)
    
    local entry_count=${#entries[@]}
    local current_index=0
    
    for entry in "${entries[@]}"; do
        current_index=$((current_index + 1))
        local basename_entry
        basename_entry=$(basename "$entry")
        local is_last_entry="false"
        
        if [[ $current_index -eq $entry_count ]]; then
            is_last_entry="true"
        fi
        
        # Determine tree characters
        local tree_char="├──"
        local next_prefix="$prefix│   "
        
        if [[ "$is_last_entry" == "true" ]]; then
            tree_char="└──"
            next_prefix="$prefix    "
        fi
        
        # Generate description based on file/directory type and name
        local description
        description=$(generate_file_description "$entry")
        
        if [[ -d "$entry" ]]; then
            echo "$prefix$tree_char $basename_entry/$description"
            # Recursively process subdirectory
            generate_complete_tree_structure "$entry" "$next_prefix" "$is_last_entry"
        else
            echo "$prefix$tree_char $basename_entry$description"
        fi
    done
}

