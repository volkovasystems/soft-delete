pattern_str = r'^(#+\s+(?:Project|Directory)\s+Structure)\s*$\n\n.*?^' + re.escape('```') + r'\n.*?^' + re.escape('```')

# Replace with canonical structure
def replace_structure(match):
    header = match.group(1)
    return header + '\n\n' + canonical_tree

