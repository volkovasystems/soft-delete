# Check for duplicate structure sections
check_for_duplicates() {
    local file="$1"
    local duplicates=0
    
    # Count occurrences of structure indicators (specifically in code blocks)
    local structure_count=0
    if [[ -f "$file" ]]; then
        # Use a more robust approach that avoids potential stdin issues
        # Count occurrences of "soft-delete/" that appear to be project roots
        structure_count=$(awk '
            /^```/ { in_code = !in_code; next }
            in_code && /^soft-delete\/$/ { count++ }
            END { print count + 0 }
        ' "$file")
        
        # Check for multiple code blocks with soft-delete/ as project root
        if [[ ${structure_count:-0} -gt 1 ]]; then
            log_error "DUPLICATE DETECTED: Found $structure_count structure sections in $file"
            duplicates=$structure_count
        fi
    fi
    
    # Check for sync header duplication
    local header_count=0
    if grep -q "🔄 REPOSITORY STRUCTURE SYNCHRONIZATION" "$file" 2>/dev/null; then
        header_count=$(grep -c "🔄 REPOSITORY STRUCTURE SYNCHRONIZATION" "$file" 2>/dev/null)
        log_error "SYNC HEADER CONTAMINATION: Found sync headers in $file (should not exist)"
        duplicates=$((duplicates + header_count))
    fi
    
    if [[ $duplicates -gt 0 ]]; then
        return 1
    else
        return 0
    fi
}

# Clean existing duplicate structures
clean_duplicates() {
    local file="$1"
    local temp_file
    temp_file=$(mktemp)
    
    log_info "Cleaning any existing duplicates in $file..."
    
    # Remove sync headers that shouldn't be in the file
    sed '/🔄 REPOSITORY STRUCTURE SYNCHRONIZATION/d; /========================================/d' "$file" > "$temp_file"
    mv "$temp_file" "$file"
    
    # Remove duplicate structure sections (keep only the first one)
    local temp_file2
    temp_file2=$(mktemp)
    
    awk '
    BEGIN { structure_found = 0; in_structure = 0; skip_structure = 0 }
    
    # Detect start of structure section
    /^#+ (Project|Directory) Structure$/ {
        if (structure_found == 0) {
            structure_found = 1
            print $0
            next
        } else {
            # This is a duplicate - skip entire section
            skip_structure = 1
            next
        }
    }
    
    # Handle content within structure sections
    structure_found == 1 && !skip_structure {
        if (/^```/) {
            if (in_structure == 0) {
                in_structure = 1
                print $0
                next
            } else {
                in_structure = 0
                structure_found = 2  # Mark as completed
                print $0
                next
            }
        }
        if (in_structure == 1 || /^$/) {
            print $0
            next
        }
        if (/^#+ /) {
            structure_found = 2  # End of structure section
            print $0
            next
        }
        print $0
        next
    }
    
    # Skip duplicate structure content
    skip_structure == 1 {
        if (/^#+ / && !/^#+ (Project|Directory) Structure$/) {
            skip_structure = 0
            print $0
        }
        next
    }
    
    # Print all other lines
    { print }
    ' "$file" > "$temp_file2"
    
    mv "$temp_file2" "$file"
    log_success "Cleaned duplicates from $file"
}

# Update file listings in documentation using canonical source
update_file_listings() {
    local file="$1"
    local structure_file="$REPO_ROOT/docs/PROJECT-STRUCTURE.md"
    local temp_file
    temp_file=$(mktemp)
    
    log_info "Updating file listings in $file using canonical source..."
    
    # Ensure PROJECT-STRUCTURE.md exists and is up-to-date
    if [[ ! -f "$structure_file" ]]; then
        log_warning "PROJECT-STRUCTURE.md not found, generating it first"
        generate_project_structure_file
    fi
    
    # Skip duplicate checking for now to avoid hanging
    # TODO: Fix check_for_duplicates function separately
    
    # Extract just the tree structure from PROJECT-STRUCTURE.md
    local canonical_tree
    canonical_tree=$(sed -n '/^```$/,/^```$/p' "$structure_file")
    
    # Look for sections that need updating
    if grep -q "### Project Structure\|## Project Structure\|# Project Structure" "$file"; then
        
        # Use simple awk approach that we know works
        local temp_canonical
        temp_canonical=$(mktemp)
        
        # Write canonical tree to temp file
        echo "$canonical_tree" > "$temp_canonical"
        
        # Use awk to replace structure sections (same logic as before but simplified)
        awk -v canonical_file="$temp_canonical" '
        BEGIN {
            # Read canonical tree
            canonical_tree = ""
            while ((getline line < canonical_file) > 0) {
                canonical_tree = canonical_tree line "\n"
            }
            close(canonical_file)
            gsub(/\n$/, "", canonical_tree)
            skip_until_next_section = 0
        }
        
        # Detect structure section headers
        /^#{1,6}[ \t]+(Project|Directory)[ \t]+Structure[ \t]*$/ {
            print $0  # Print the header
            print ""  # Print blank line
            print canonical_tree  # Print canonical structure
            skip_until_next_section = 1
            next
        }
        
        # Skip content until next section when in replacement mode
        skip_until_next_section == 1 {
            # Look for next markdown header or end of file
            if (/^#{1,6}[ \t]+/ && !/^#{1,6}[ \t]+(Project|Directory)[ \t]+Structure[ \t]*$/) {
                skip_until_next_section = 0
                print $0
            }
            # Skip everything else until next section
            next
        }
        
        # Print all other lines
        { print }
        ' "$file" > "$temp_file"
        
        # Clean up temp files
        rm -f "$temp_canonical"
        
        if [[ -s "$temp_file" ]]; then
            mv "$temp_file" "$file"
            log_success "Updated structure in $file from canonical source"
        else
            rm "$temp_file"
            log_error "Failed to update $file - temp file is empty"
            return 1
        fi
    else
        rm -f "$temp_file"
        log_info "No structure sections found in $file to update"
    fi
}

# Update script references in documentation
update_script_references() {
    local file="$1"
    local temp_file
    temp_file=$(mktemp)
    
    log_info "Validating script references in $file..."
    
    # Find all script references and check if they exist
    local script_refs
    script_refs=$(grep -o 'scripts/[a-zA-Z0-9_-]*\.sh' "$file" 2>/dev/null || true)
    
    local updates_needed=false
    if [[ -n "$script_refs" ]]; then
        while IFS= read -r script_ref; do
            if [[ ! -f "$script_ref" ]]; then
                log_warning "Referenced script missing: $script_ref"
                updates_needed=true
            fi
        done <<< "$script_refs"
    fi
    
    if [[ "$updates_needed" == "true" ]]; then
        log_warning "Script references in $file need manual review"
    fi
    
    rm -f "$temp_file"
}

