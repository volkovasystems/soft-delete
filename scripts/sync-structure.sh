# Generate comprehensive PROJECT-STRUCTURE.md file
generate_project_structure_file() {
    local structure_file="$REPO_ROOT/docs/PROJECT-STRUCTURE.md"
    local timestamp
    timestamp=$(date -u +"%Y-%m-%d %H:%M:%S UTC")
    
    log_info "Generating canonical PROJECT-STRUCTURE.md file..."
    
    cat > "$structure_file" << 'EOF'
# Project Structure

> **Single Source of Truth**: This file is the canonical reference for the soft-delete project structure. All documentation structure sections are synchronized from this file.
> 
> **Auto-generated by sync-structure.sh** - Do not edit manually. Changes will be overwritten during synchronization.

## Directory Tree

EOF
    
    # Generate the tree structure
    generate_directory_tree >> "$structure_file"
    
    cat >> "$structure_file" << 'EOF'

## Structure Guidelines

### File Organization Principles

1. **Configuration at Root**: Primary configuration files (`.editorconfig`, `.gitignore`, etc.) remain at project root
2. **Documentation Hierarchy**: 
   - Technical docs in `docs/` directory
   - Warp AI context in `.warp/` directory
   - Project overview in root `README.md`
3. **Script Organization**: All utility scripts in `scripts/` directory with clear naming
4. **Test Structure**: All tests in `tests/` directory using BATS framework
5. **Build Artifacts**: Compiled binaries in `bin/`, distribution files in `dist/`

### Directory Purposes

- **`.github/`**: GitHub-specific configuration and workflows
- **`.warp/`**: AI agent configuration and development protocols
- **`bin/`**: Compiled executable binaries
- **`docs/`**: Comprehensive technical documentation
- **`examples/`**: Usage examples and demonstrations
- **`scripts/`**: Development and maintenance utilities
- **`tests/`**: Test suites and testing infrastructure

### Validation Requirements

- All scripts must be documented in API.md
- Cross-references must be valid and up-to-date
- File counts must match actual repository state
- Executable references must use correct naming conventions

EOF
    
    echo "*Last Updated: $timestamp*" >> "$structure_file"
    
    log_success "Generated PROJECT-STRUCTURE.md with $(wc -l < "$structure_file") lines"
    return 0
}

# Generate complete directory tree showing ALL files and directories for transparency
generate_directory_tree() {
    # Generate complete tree structure for full transparency
    echo '```'
    echo "soft-delete/"
    
    # First pass: generate tree without comments to find the longest line
    local tree_lines=()
    while IFS= read -r line; do
        tree_lines+=("$line")
    done < <(generate_complete_tree_structure "." "" "false" "no-comments")
    
    # Find the longest line length
    local max_length=0
    for line in "${tree_lines[@]}"; do
        local line_length=${#line}
        if [[ $line_length -gt $max_length ]]; then
            max_length=$line_length
        fi
    done
    
    # Set global alignment column (longest line + minimum 2 spaces)
    GLOBAL_COMMENT_COLUMN=$((max_length + 2))
    
    # Second pass: generate tree with comments aligned to the calculated column
    generate_complete_tree_structure "." "" "false" "with-comments"
    
    echo '```'
}

# Helper function to recursively generate complete tree structure
generate_complete_tree_structure() {
    local current_dir="$1"
    local prefix="$2"
    local is_last="$3"
    local comment_mode="${4:-with-comments}"  # Default to with-comments for backward compatibility
    
    # Skip .git directory for readability but include everything else
    if [[ "$(basename "$current_dir")" == ".git" ]]; then
        return
    fi
    
    # Get all entries (files and directories) sorted
    local entries=()
    while IFS= read -r -d '' entry; do
        entries+=("$entry")
    done < <(find "$current_dir" -maxdepth 1 -mindepth 1 ! -name ".git" -print0 | sort -z)
    
    local entry_count=${#entries[@]}
    local current_index=0
    
    for entry in "${entries[@]}"; do
        current_index=$((current_index + 1))
        local basename_entry
        basename_entry=$(basename "$entry")
        local is_last_entry="false"
        
        if [[ $current_index -eq $entry_count ]]; then
            is_last_entry="true"
        fi
        
        # Determine tree characters
        local tree_char="├──"
        local next_prefix="$prefix│   "
        
        if [[ "$is_last_entry" == "true" ]]; then
            tree_char="└──"
            next_prefix="$prefix    "
        fi
        
        if [[ -d "$entry" ]]; then
            # Handle directory
            local tree_line="$prefix$tree_char $basename_entry/"
            if [[ "$comment_mode" == "no-comments" ]]; then
                echo "$tree_line"
            else
                # Generate description for directories
                local description
                description=$(generate_file_description "$entry" "$prefix$tree_char " "$comment_mode")
                echo "$tree_line$description"
            fi
            # Recursively process subdirectory
            generate_complete_tree_structure "$entry" "$next_prefix" "$is_last_entry" "$comment_mode"
        else
            # Handle file
            local tree_line="$prefix$tree_char $basename_entry"
            if [[ "$comment_mode" == "no-comments" ]]; then
                echo "$tree_line"
            else
                # Generate description for files
                local description
                description=$(generate_file_description "$entry" "$prefix$tree_char " "$comment_mode")
                echo "$tree_line$description"
            fi
        fi
    done
}

