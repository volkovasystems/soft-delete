   - Project overview in root `README.md`
3. **Script Organization**: All utility scripts in `scripts/` directory with clear naming
4. **Test Structure**: All tests in `tests/` directory using BATS framework
5. **Build Artifacts**: Compiled binaries in `bin/`, distribution files in `dist/`

